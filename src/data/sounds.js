// ตารางจับคู่ "เสียงในเกม" กับ "ชื่อไฟล์จริงใน assets/"
//
// แบบเดียวกับ data/icons.js — เจ้าของโปรเจกต์อัปไฟล์มาโดยไม่เปลี่ยนชื่อ
// การจับคู่จึงมาอยู่ที่นี่ที่เดียว ห้ามพิมพ์ชื่อไฟล์เสียงซ้ำที่อื่น
//
// ⚠️ ชื่อไฟล์จริงสะกดไม่ตรงกับที่คุยไว้ และบางอันมี `!` หรือเว้นวรรค
//    ห้ามเดาชื่อเอง ให้ยึดตารางนี้เท่านั้น (soundPath() encode ให้แล้ว)

const DIR = 'assets/';

// ── ระดับเสียง: วัดมาจากไฟล์จริง ไม่ได้เดา ──────────────────────
//
// วัด "RMS ของช่วงที่ดังที่สุด (หน้าต่าง 150 มิลลิวินาที)" ของทุกไฟล์ แล้วตั้ง gain
// ให้ทุกไฟล์ดังเท่ากันที่ระดับเป้าหมาย ค่าที่วัดได้ต่างกันมากถึง 24 dB:
//
//   result 0.641 · op-down 0.588 · London Bridge 0.405 · wrong-rhythm 0.299
//   success 0.271 · point-counter 0.214 · click 0.042  ← เบากว่าเพลง 24 dB
//
// เพราะ click เบามาก การใช้ `el.volume` (ทำได้แค่ 0..1 คือ "ลดอย่างเดียว")
// จึงดันให้ดังเท่าคนอื่นไม่ได้ ต้องเดินผ่าน Web Audio ที่ตั้ง gain เกิน 1 ได้
// รายละเอียดอยู่ที่ ui/audio.js
const BGM_TARGET = 0.12;  // เพลงประกอบ — ต้องเบากว่า เพราะเล่นค้างอยู่ตลอด
const SFX_TARGET = 0.22;  // เสียงเอฟเฟกต์ — ดังกว่าเพลง เพื่อให้ได้ยินทะลุเพลงขึ้นมา

const gainFor = (target, measured) => +(target / measured).toFixed(2);

/**
 * kind:
 *   'sfx' = เสียงสั้น เล่นซ้อนกันได้ (ต้องมีหลายก๊อปปี้ ไม่งั้นกดรัว ๆ แล้วเสียงตัดกันเอง)
 *   'bgm' = เพลงประจำฉาก เล่นทีละเพลง วนซ้ำ สลับด้วย setBgm()
 *   'cue' = เสียงยาวเฉพาะกิจ เล่นทับเพลงได้ (ตอนนี้มีแค่เสียงนับคะแนน)
 *
 * lazy: true = "ยังไม่ต้องรีบโหลด" — ไฟล์ใหญ่ที่ยังไม่ได้ใช้ในไม่กี่วินาทีแรก
 *   ไฟล์เสียงรวมกัน 13 MB ถ้าโหลดพร้อมกันหมดตอนเปิดเกม เน็ตมือถือจะตันจนหน้าแรกหนืด
 *   ตัวที่ lazy จะเริ่มโหลดหลังผู้เล่นแตะหน้าปกไปแล้ว 2 วินาที (ดู ui/audio.js)
 *   ตอนนั้นยังอยู่หน้าเมนู/หน้าสอนเล่น เหลือเวลาโหลดอีกเป็นนาทีก่อนจะได้ใช้จริง
 */
export const SOUNDS = {
  // ── เสียงสั้น ──────────────────────────────────────────────────
  click:   { file: 'click.mp3',                kind: 'sfx', pool: 4, gain: gainFor(SFX_TARGET, 0.0417) },
  opDown:  { file: 'op-down.mp3',              kind: 'sfx', pool: 2, gain: gainFor(SFX_TARGET, 0.5878) },
  success: { file: 'success-notification.mp3', kind: 'sfx', pool: 2, gain: gainFor(SFX_TARGET, 0.2709) },
  // เสียงกดพลาดในมินิเกมจังหวะ (ui/qte.js) — ยาว 3 วิ จึงมี 2 ก๊อปปี้ กันพลาดรัว ๆ แล้วเสียงตัดกันเอง
  wrongRhythm: { file: 'wrong-rhythm.mp3', kind: 'sfx', pool: 2, gain: gainFor(SFX_TARGET, 0.2993) },

  // ── เพลงประจำฉาก (วนซ้ำทั้งหมด) ───────────────────────────────
  // หน้าเมนูและหน้าสรุปผล — เล่นต่อเนื่องข้ามหน้า Settings/Intel ไม่เริ่มใหม่
  menu:         { file: 'result.mp3',        kind: 'bgm', gain: gainFor(BGM_TARGET, 0.6412) },
  // หน้าเกมทั้งเกม (7:45 — ยาวกว่าเกมหนึ่งรอบ แต่ตั้งวนซ้ำไว้เผื่อเล่นช้า)
  // เจ้าของตัดเพลงเร่งช่วงท้ายทิ้งแล้ว ใช้เพลงนี้ยาวตั้งแต่ต้นจนจบเกม
  gameMain:     { file: 'London Bridge.mp3', kind: 'bgm', lazy: true, gain: gainFor(BGM_TARGET, 0.4047) },

  // ── เสียงยาวเฉพาะกิจ ─────────────────────────────────────────
  // ตอนตัวเลขคะแนนวิ่งในหน้า Result — เล่นทับเพลงหน้าสรุปผล
  pointCounter: { file: 'point-counter.mp3', kind: 'cue', lazy: true, gain: gainFor(SFX_TARGET, 0.2144) },
};

export function soundPath(key) {
  const spec = SOUNDS[key];
  // ชื่อไฟล์มีทั้ง `!` และเว้นวรรค — ต้อง encode ก่อนใช้เป็น URL เสมอ
  return spec ? DIR + encodeURIComponent(spec.file) : null;
}
