// ตารางจับคู่ "เสียงในเกม" กับ "ชื่อไฟล์จริงใน assets/"
//
// แบบเดียวกับ data/icons.js — เจ้าของโปรเจกต์อัปไฟล์มาโดยไม่เปลี่ยนชื่อ
// การจับคู่จึงมาอยู่ที่นี่ที่เดียว ห้ามพิมพ์ชื่อไฟล์เสียงซ้ำที่อื่น
//
// ⚠️ ชื่อไฟล์บางอันมี `!` และสะกดไม่ตรงกันกับที่คุยไว้ (success ไม่ใช่ sucess)
//    เพราะงั้นห้ามเดาชื่อเอง ให้ยึดตารางนี้เท่านั้น

const DIR = 'assets/';

/**
 * kind:
 *   'sfx'  = เสียงสั้น เล่นซ้อนกันได้ (ต้องมีหลายก๊อปปี้ ไม่งั้นกดรัว ๆ แล้วเสียงตัดกันเอง)
 *   'loop' = เสียงยาว เล่นทีละอัน หยุด/เล่นต่อได้
 */
export const SOUNDS = {
  // ── เสียงสั้น ──────────────────────────────────────────────────
  // ทุกการกดปุ่ม/ลากไอคอนในเกม (เจ้าของย้ำว่าอันนี้สำคัญ ต้องมีทุกที่)
  click: { file: 'click.mp3', kind: 'sfx', pool: 4, volume: 0.7 },

  // จนท. บาดเจ็บ/หมดสติ หรือช่วยไม่สำเร็จ
  opDown: { file: 'op-down.mp3', kind: 'sfx', pool: 2, volume: 0.9 },

  // จนท. หายบาดเจ็บ/หมดสติ หรือช่วยสำเร็จ
  success: { file: 'success-notification.mp3', kind: 'sfx', pool: 2, volume: 0.9 },

  // ── เสียงยาว ──────────────────────────────────────────────────
  // เข้าหน้า Result (11.45 วิ) — ออกจากหน้าเมื่อไหร่หยุดทันที
  result: { file: 'result.mp3', kind: 'loop', volume: 0.8, loop: false },

  // เหลือเวลาจริงอีก 1 นาที (51.67 วิ) — หยุดตามตอนกดหยุดเวลา เล่นต่อตอนเดินเวลาต่อ
  lastMinute: { file: '1minuteleft!.mp3', kind: 'loop', volume: 0.8, loop: false },

  // ตอนตัวเลขคะแนนวิ่งในหน้า Result (10.03 วิ)
  // ไฟล์ยาวกว่าอนิเมชั่น (~2.5 วิ) มาก ปกติจึงถูกสั่งหยุดก่อนจบเสมอ
  // ตั้ง loop ไว้เผื่อกรณีอนิเมชั่นยาวกว่าไฟล์ ตามที่เจ้าของสั่ง ("ยังไม่เสร็จก็เล่นอีกรอบ")
  pointCounter: { file: 'point-counter.mp3', kind: 'loop', volume: 0.7, loop: true },
};

export function soundPath(key) {
  const spec = SOUNDS[key];
  // ชื่อไฟล์มี `!` — ต้อง encode ก่อน ไม่งั้นบาง server/browser ตีความผิด
  return spec ? DIR + encodeURIComponent(spec.file) : null;
}
